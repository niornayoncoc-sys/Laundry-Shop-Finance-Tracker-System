private void loadReports() {
    DefaultTableModel model = getReportModel();
    model.setRowCount(0);

    String sql =
        "SELECT o.order_id, o.order_number, c.full_name, " +
        "s.service_name, o.weight_kg, o.total_price, o.status, " +
        "COALESCE(SUM(p.amount_paid), 0) AS paid " +
        "FROM orders o " +
        "JOIN customers c ON o.customer_id = c.customer_id " +
        "JOIN services s ON o.service_id = s.service_id " +
        "LEFT JOIN payments p ON o.order_id = p.order_id " +
        "GROUP BY o.order_id, o.order_number, c.full_name, " +
        "s.service_name, o.weight_kg, o.total_price, o.status " +
        "ORDER BY o.order_id DESC";

    double sales = 0.0;

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement ps = conn.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            double paid = rs.getDouble("paid");
            sales += paid;

            model.addRow(new Object[]{
                rs.getInt("order_id"),
                rs.getString("order_number"),
                rs.getString("full_name"),
                rs.getString("service_name"),
                rs.getDouble("weight_kg"),
                rs.getDouble("total_price"),
                paid,
                rs.getString("status")
            });
        }

        lblTotalSale.setText(
            String.format("Total Payments Received: ₱%.2f", sales)
        );

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(
            this,
            "Unable to load reports:\n" + ex.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}

